/**
 * Converts a Sessionize event into the site's programme data:
 *
 *   deno task sessionize
 *
 * Fetches the event's two "API / Embed" views (the endpoint is `endpoint`
 * in src/_data/sessionize.yaml), turns them into the `agenda` and
 * `speakers` concepts (../sessionize.ts) and writes src/_data/agenda.yaml,
 * src/_data/speakers.yaml and the speakers' photos under
 * src/assets/speakers/ (pruning the ones it mirrored that are no longer
 * used; a portrait of the site's own in that folder, named by a patch, is
 * left alone). The build never talks to Sessionize; run this, review the
 * diff, commit.
 *
 * The two files belong to this script: a correction by hand goes in
 * src/_data/patches/ (../program.ts), which it never touches. Nothing is
 * written until every download succeeded.
 *
 * Paths are relative to the working directory (`--src <dir>`, default
 * `src`), so the script works from an instance whether the theme is local
 * or a URL. The task's permission set must allow reading `./src` and
 * writing the two files and the photo folder.
 */

import { parse, stringify } from "lume/deps/yaml.ts";
import { parseArgs } from "lume/deps/cli.ts";
import {
  type ApiAll,
  type ApiGridDay,
  type Converted,
  fromSessionize,
  isMirrored,
  PHOTO_URL,
} from "../sessionize.ts";

/** The two views `fromSessionize()` combines. */
const VIEWS = ["All", "GridSmart"] as const;

/** Site paths of the two files this script writes. */
export const AGENDA_FILE = "/_data/agenda.yaml";
export const SPEAKERS_FILE = "/_data/speakers.yaml";

/** One concept as YAML: a header saying where it came from and where to correct it, then the data. */
export function renderYaml(
  concept: "agenda" | "speakers",
  data: Converted["agenda"] | Converted["speakers"],
  endpoint: string,
): string {
  const header = [
    `# Generated by \`deno task sessionize\` from Sessionize event ${endpoint}; do not edit.`,
    `# The next run overwrites this file. Corrections go in _data/patches/${concept}.yaml,`,
    `# which is merged over it at build time (see the organizer handbook's Sessionize guide).`,
    "",
  ].join("\n");
  return header + stringify(data);
}

async function download(url: string): Promise<Response> {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(
      `Sessionize request failed: ${response.status} ${response.statusText} for ${url}`,
    );
  }
  return response;
}

async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path);
    return true;
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return false;
    throw error;
  }
}

async function main() {
  const args = parseArgs(Deno.args, {
    string: ["src"],
    boolean: ["help"],
    default: { src: "src" },
  });
  if (args.help) {
    console.log(
      "usage: sessionize.ts [--src <dir>]\n\n" +
        "Converts the Sessionize event named by `endpoint` in <src>/_data/sessionize.yaml\n" +
        "into <src>/_data/agenda.yaml and <src>/_data/speakers.yaml, and mirrors the\n" +
        "speakers' photos into <src>/assets/speakers/. <dir> defaults to \"src\",\n" +
        "relative to the working directory.",
    );
    return;
  }
  // A site path ("/_data/agenda.yaml") on disk, under the source folder.
  const src = args.src.replace(/\/+$/, "");
  const onDisk = (sitePath: string) => `${src}${sitePath}`;

  const { endpoint } = parse(
    await Deno.readTextFile(onDisk("/_data/sessionize.yaml")),
  ) as { endpoint: string };
  if (!/^\w+$/.test(endpoint)) {
    throw new Error(`Unexpected Sessionize endpoint id: ${endpoint}`);
  }
  const api = `https://sessionize.com/api/v2/${endpoint}/view`;

  const [all, grid] = await Promise.all(
    VIEWS.map(async (view) => (await download(`${api}/${view}`)).json()),
  ) as [ApiAll, ApiGridDay[]];

  const converted = fromSessionize(all, grid);

  const missing: string[] = [];
  for (const name of converted.photos) {
    if (!await exists(onDisk(PHOTO_URL + name))) missing.push(name);
  }
  const downloaded = await Promise.all(missing.map(async (name) => {
    const url = `https://cdn.sessionize.com/image/${name}`;
    const response = await download(url);
    const type = response.headers.get("content-type") ?? "";
    if (!type.startsWith("image/")) {
      throw new Error(`Expected an image, got "${type}" for ${url}`);
    }
    return [name, new Uint8Array(await response.arrayBuffer())] as const;
  }));


  await Deno.writeTextFile(
    onDisk(AGENDA_FILE),
    renderYaml("agenda", converted.agenda, endpoint),
  );
  await Deno.writeTextFile(
    onDisk(SPEAKERS_FILE),
    renderYaml("speakers", converted.speakers, endpoint),
  );

  const photoDir = onDisk(PHOTO_URL);
  await Deno.mkdir(photoDir, { recursive: true });
  for (const [name, bytes] of downloaded) {
    await Deno.writeFile(`${photoDir}${name}`, bytes);
  }
  const keep = new Set(converted.photos);
  const removed: string[] = [];
  for await (const entry of Deno.readDir(photoDir)) {
    if (entry.isFile && isMirrored(entry.name) && !keep.has(entry.name)) {
      await Deno.remove(`${photoDir}${entry.name}`);
      removed.push(entry.name);
    }
  }

  const { agenda, speakers } = converted;
  console.log(
    `Sessionize ${endpoint}: ${agenda.sessions.length} talks ` +
      `(${agenda.sessions.filter((s) => s.cancelled).length} cancelled), ` +
      `${agenda.breaks?.length ?? 0} breaks, ${speakers.length} speakers; ` +
      `photos: ${downloaded.length} downloaded, ${removed.length} removed, ` +
      `${keep.size - downloaded.length} unchanged.`,
  );
}

if (import.meta.main) await main();
